/** Los 12 temas con letra, en orden de album (Noise queda afuera). */
export const LYRIC_TRACKS = ALBUM.filter((t) => !t.instrumental);

/** Solo los titulos, en orden de album. Lo consume el JSON-LD del disco. */
export const TRACKS = ALBUM.map((t) => t.title);

/** Divide una letra en estrofas: linea en blanco = corte de estrofa. */
export const toStanzas = (lyrics) =>
  lyrics
    .trim()
    .split(/\n\s*\n/)
    .map((stanza) => stanza.split("\n"));

/** Vecinos circulares dentro de los 12 temas con letra. */
export const neighbours = (slug) => {
  const i = LYRIC_TRACKS.findIndex((t) => t.slug === slug);
  const len = LYRIC_TRACKS.length;
  return {
    prev: LYRIC_TRACKS[(i - 1 + len) % len],
    next: LYRIC_TRACKS[(i + 1) % len],
  };
};
